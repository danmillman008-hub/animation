#!/usr/bin/env python3
"""Raster → vector: trace a flat-colour illustration (magenta-keyed background)
into SVG <path> data and emit a ready-to-use React component.

    python3 tools/trace_vignette.py assets/vignette_src.png src/scene/EndVignette.tsx

Pipeline: magenta chroma-key → alpha | top-N colour quantisation | per-colour
mask clean-up (morphology + small-blob cull) | OpenCV contour extraction with
holes (RETR_CCOMP) | Douglas-Peucker simplification | evenodd SVG paths.
"""
import sys
import numpy as np
import cv2
from PIL import Image

SRC = sys.argv[1] if len(sys.argv) > 1 else 'assets/vignette_src.png'
OUT = sys.argv[2] if len(sys.argv) > 2 else 'src/scene/EndVignette.tsx'
N_COLORS = 12
EPS = 1.1          # Douglas-Peucker tolerance in source px
MIN_AREA = 60      # px² — cull anti-alias confetti

img = np.array(Image.open(SRC).convert('RGB')).astype(np.int16)
h, w, _ = img.shape

# ---- chroma-key the magenta backdrop ----
dist = np.abs(img - np.array([255, 0, 255])).sum(axis=2)
alpha = dist > 90
ys, xs = np.where(alpha)
y0, y1, x0, x1 = ys.min(), ys.max(), xs.min(), xs.max()
print(f'content bbox: x {x0}..{x1}  y {y0}..{y1}  ({x1-x0+1}×{y1-y0+1})')

pix = img[alpha]
# ---- quantise to the N most common colours (rounded space) ----
rounded = ((pix // 24) * 24 + 12).astype(np.int64)
keys, counts = np.unique(rounded[:, 0] * 65536 + rounded[:, 1] * 256 + rounded[:, 2], return_counts=True)
order = np.argsort(-counts)[:N_COLORS]
palette = np.array([[(k // 65536) % 256, (k // 256) % 256, k % 256] for k in keys[order]])

lab = np.full((h, w), -1, np.int32)
d2 = ((img[:, :, None, :] - palette[None, None, :, :]) ** 2).sum(axis=3)
nearest = np.argmin(d2, axis=2)
lab[alpha] = nearest[alpha]

# ---- per-colour masks → contours → path data ----
paths = []
for ci in range(len(palette)):
    mask = ((lab == ci) & alpha).astype(np.uint8) * 255
    mask = cv2.morphologyEx(mask, cv2.MORPH_CLOSE, np.ones((3, 3), np.uint8))
    mask = cv2.morphologyEx(mask, cv2.MORPH_OPEN, np.ones((3, 3), np.uint8))
    n, comp, stats, _ = cv2.connectedComponentsWithStats(mask, 8)
    clean = np.zeros_like(mask)
    for k in range(1, n):
        if stats[k, cv2.CC_STAT_AREA] >= MIN_AREA:
            clean[comp == k] = 255
    if clean.sum() == 0:
        continue
    contours, hier = cv2.findContours(clean, cv2.RETR_CCOMP, cv2.CHAIN_APPROX_SIMPLE)
    d = []
    pts_total = 0
    for c in contours:
        if cv2.contourArea(c) < MIN_AREA / 2:
            continue
        poly = cv2.approxPolyDP(c[:, 0, :].astype(np.float32), EPS, True).reshape(-1, 2)
        if len(poly) < 3:
            continue
        pts = ' '.join(f'{p[0]-x0:.1f} {p[1]-y0:.1f}' for p in poly)
        d.append(f'M {pts} Z')
        pts_total += len(poly)
    if not d:
        continue
    r, g, b = palette[ci]
    paths.append((int(clean.sum()), f'#{r:02x}{g:02x}{b:02x}', ''.join(d), pts_total))

paths.sort(key=lambda p: -p[0])  # biggest shapes first, details on top
bw, bh = x1 - x0 + 1, y1 - y0 + 1
total_pts = sum(p[3] for p in paths)
print(f'{len(paths)} colour layers, {total_pts} polygon points')

with open(OUT, 'w', encoding='utf-8') as f:
    f.write("""import React from 'react';

/**
 * AUTO-GENERATED by tools/trace_vignette.py — do not edit by hand.
 * Traced from an AI-generated flat illustration (assets/vignette_src.png):
 * magenta chroma-key → colour quantisation → OpenCV contours → simplified
 * evenodd SVG paths. Pure vector, no raster asset ships with the video.
 */
export const VIGNETTE_W = %d;
export const VIGNETTE_H = %d;

export const EndVignette: React.FC<{x: number; y: number; w: number; opacity?: number}> = ({x, y, w, opacity = 1}) => (
  <g transform={`translate(${x} ${y}) scale(${w / VIGNETTE_W})`} opacity={opacity} fillRule="evenodd">
""" % (bw, bh))
    for area, color, d, _ in paths:
        f.write(f'    <path fill="{color}" d="{d}" />\n')
    f.write('  </g>\n);\n')
print('wrote', OUT)
